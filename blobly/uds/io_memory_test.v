fn test_f186_reads_the_active_session() {
	mut s := default_server()
	assert s.handle([u8(0x22), 0xF1, 0x86]) == [u8(0x62), 0xF1, 0x86, 0x01]
	assert s.handle([u8(0x10), 0x03])[0] == 0x50
	assert s.handle([u8(0x22), 0xF1, 0x86]) == [u8(0x62), 0xF1, 0x86, 0x03]
	assert s.handle([u8(0x2E), 0xF1, 0x86, 0x01]) == [u8(0x7F), 0x2E, 0x31]
	assert s.handle([u8(0x11), 0x01])[0] == 0x51
	assert s.handle([u8(0x22), 0xF1, 0x86]) == [u8(0x62), 0xF1, 0x86, 0x01]
}

fn test_f186_listed_in_the_table_is_its_value() {
	mut s := Server{
		dids: {
			u16(0xF186): [u8(0x7A)]
		}
	}
	assert s.handle([u8(0x10), 0x03])[0] == 0x50
	assert s.handle([u8(0x22), 0xF1, 0x86]) == [u8(0x62), 0xF1, 0x86, 0x7A]
}

fn test_f186_on_a_described_server() {
	mut s := server_from(ServerSpec{
		dids: [DidSpec{
			id:   0x0100
			data: [u8(9)]
		}]
	})
	assert s.handle([u8(0x22), 0xF1, 0x86]) == [u8(0x62), 0xF1, 0x86, 0x01]
	assert s.handle([u8(0x10), 0x03])[0] == 0x50
	assert s.handle([u8(0x22), 0x01, 0x00, 0xF1, 0x86]) == [u8(0x62), 0x01, 0x00, 0x09, 0xF1, 0x86,
		0x03]
}

