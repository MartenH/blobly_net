fn test_io_control_sets_freezes_and_returns_control() {
	mut s := default_server()
	s.declare_io(0x1234, 1)
	assert s.handle([u8(0x22), 0x12, 0x34]) == [u8(0x62), 0x12, 0x34, 0x00]
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x03, 0x05]) == [u8(0x6F), 0x12, 0x34, 0x03, 0x05]
	assert s.handle([u8(0x22), 0x12, 0x34]) == [u8(0x62), 0x12, 0x34, 0x05]
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x02]) == [u8(0x6F), 0x12, 0x34, 0x02, 0x05]
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x00]) == [u8(0x6F), 0x12, 0x34, 0x00, 0x00]
	assert s.handle([u8(0x22), 0x12, 0x34]) == [u8(0x62), 0x12, 0x34, 0x00]
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x03, 0x07])[0] == 0x6F
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x01]) == [u8(0x6F), 0x12, 0x34, 0x01, 0x00]
}

fn test_the_default_session_and_a_reset_return_io_control() {
	mut s := default_server()
	s.declare_io(0x1234, 1)
	assert s.handle([u8(0x10), 0x03])[0] == 0x50
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x03, 0x05])[0] == 0x6F
	assert s.handle([u8(0x10), 0x03])[0] == 0x50 // another non-default session keeps it
	assert s.handle([u8(0x22), 0x12, 0x34]) == [u8(0x62), 0x12, 0x34, 0x05]
	assert s.handle([u8(0x10), 0x01])[0] == 0x50
	assert s.handle([u8(0x22), 0x12, 0x34]) == [u8(0x62), 0x12, 0x34, 0x00]
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x03, 0x06])[0] == 0x6F
	assert s.handle([u8(0x11), 0x01])[0] == 0x51
	assert s.handle([u8(0x22), 0x12, 0x34]) == [u8(0x62), 0x12, 0x34, 0x00]
}

fn test_io_control_refusals() {
	mut s := default_server()
	s.declare_io(0x1234, 2)
	assert s.handle([u8(0x2F), 0x12]) == [u8(0x7F), 0x2F, 0x13]
	assert s.handle([u8(0x2F), 0x43, 0x21, 0x03, 0x01, 0x02]) == [u8(0x7F), 0x2F, 0x31] // undeclared
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x04]) == [u8(0x7F), 0x2F, 0x31] // no such parameter
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x03, 0x01]) == [u8(0x7F), 0x2F, 0x13] // one byte short
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x00, 0x00]) == [u8(0x7F), 0x2F, 0x13]
}

fn test_a_write_to_an_io_did_takes_its_declared_size() {
	mut s := default_server()
	s.declare_io(0x1234, 2)
	mut big := [u8(0x2E), 0x12, 0x34]
	big << []u8{len: 4092}
	assert s.handle(big) == [u8(0x7F), 0x2E, 0x13]
	assert s.handle([u8(0x2E), 0x12, 0x34, 0x01]) == [u8(0x7F), 0x2E, 0x13]
	assert s.handle([u8(0x2E), 0x12, 0x34, 0x01, 0x02]) == [u8(0x6E), 0x12, 0x34]
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x02]) == [u8(0x6F), 0x12, 0x34, 0x02, 0x01, 0x02]
	assert s.handle([u8(0x2E), 0x43, 0x21, 0x01, 0x02, 0x03])[0] == 0x6E // not an IO DID
}

fn test_a_described_write_to_an_io_did_takes_its_declared_size() {
	mut s := server_from(ServerSpec{
		dids: [DidSpec{
			id:       0x1234
			data:     [u8(0)]
			writable: true
		}]
	})
	s.declare_io(0x1234, 2)
	assert s.handle([u8(0x2E), 0x12, 0x34, 0x07]) == [u8(0x7F), 0x2E, 0x13]
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x02]) == [u8(0x6F), 0x12, 0x34, 0x02, 0x00, 0x00]
}

fn test_io_control_never_answers_past_the_carrier() {
	mut s := server_from(ServerSpec{
		max_response: 8
	})
	s.declare_io(0x1234, 4)
	s.dids[0x1234] = []u8{len: 5} // however it got there
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x02]) == [u8(0x7F), 0x2F, 0x14]
	assert s.dids[0x1234].len == 5
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x00]) == [u8(0x6F), 0x12, 0x34, 0x00, 0x00, 0x00, 0x00,
		0x00]
}

fn test_memory_without_ranges_is_not_supported() {
	mut s := default_server()
	assert s.handle([u8(0x23), 0x14, 0x20, 0x00, 0x00, 0x00, 0x01]) == [u8(0x7F), 0x23, 0x11]
	assert s.handle([u8(0x3D), 0x14, 0x20, 0x00, 0x00, 0x00, 0x01, 0xAA]) == [
		u8(0x7F),
		0x3D,
		0x11,
	]
}

fn test_memory_reads_zeros_and_what_was_written() {
	mut s := default_server()
	s.declare_memory(0x2000_0000, 256)
	// ALFID 0x24: a 2-byte size, a 4-byte address
	mut want := [u8(0x63)]
	want << []u8{len: 16}
	assert s.handle([u8(0x23), 0x24, 0x20, 0x00, 0x00, 0x00, 0x00, 0x10]) == want
	assert s.handle([u8(0x3D), 0x24, 0x20, 0x00, 0x00, 0x10, 0x00, 0x02, 0xAA, 0xBB]) == [
		u8(0x7D),
		0x24,
		0x20,
		0x00,
		0x00,
		0x10,
		0x00,
		0x02,
	]
	assert s.handle([u8(0x23), 0x14, 0x20, 0x00, 0x00, 0x0F, 0x04]) == [u8(0x63), 0x00, 0xAA, 0xBB,
		0x00]
	// the range's last byte, and one past it
	assert s.handle([u8(0x23), 0x14, 0x20, 0x00, 0x00, 0xFF, 0x01]) == [u8(0x63), 0x00]
	assert s.handle([u8(0x23), 0x14, 0x20, 0x00, 0x00, 0xFF, 0x02]) == [u8(0x7F), 0x23, 0x31]
}

fn test_memory_refusals() {
	mut s := default_server()
	s.declare_memory(0x1000, 16)
	assert s.handle([u8(0x23), 0x12, 0x0F, 0xFF, 0x01]) == [u8(0x7F), 0x23, 0x31] // below the range
	assert s.handle([u8(0x23), 0x12, 0x10, 0x00]) == [u8(0x7F), 0x23, 0x13] // the size is missing
	assert s.handle([u8(0x23), 0x12, 0x10, 0x00, 0x01, 0x00]) == [u8(0x7F), 0x23, 0x13] // a byte too many
	assert s.handle([u8(0x23), 0x02, 0x10, 0x00]) == [u8(0x7F), 0x23, 0x31] // no size field
	assert s.handle([u8(0x23), 0x12, 0x10, 0x00, 0x00]) == [u8(0x7F), 0x23, 0x31] // nothing to read
	assert s.handle([u8(0x23)]) == [u8(0x7F), 0x23, 0x13]
	assert s.handle([u8(0x3D), 0x12, 0x10, 0x00, 0x02, 0xAA]) == [u8(0x7F), 0x3D, 0x13] // short record
	assert s.handle([u8(0x3D), 0x12, 0x20, 0x00, 0x01, 0xAA]) == [u8(0x7F), 0x3D, 0x31]
}

fn test_a_described_server_gates_them_by_its_table() {
	mut s := server_from(ServerSpec{
		dids:     [DidSpec{
			id:   0x0100
			data: [u8(0)]
		}]
		table:    true
		services: [ServiceSpec{
			sid: 0x10
		}, ServiceSpec{
			sid: 0x22
		}, ServiceSpec{
			sid:      0x2F
			sessions: in_extended
		}]
	})
	s.declare_io(0x1234, 1)
	s.declare_memory(0x1000, 4)
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x03, 0x05]) == [u8(0x7F), 0x2F, 0x7F]
	assert s.handle([u8(0x10), 0x03])[0] == 0x50
	assert s.handle([u8(0x2F), 0x12, 0x34, 0x03, 0x05]) == [u8(0x6F), 0x12, 0x34, 0x03, 0x05]
	assert s.handle([u8(0x22), 0x12, 0x34]) == [u8(0x62), 0x12, 0x34, 0x05]
	assert s.handle([u8(0x2E), 0x12, 0x34, 0x01]) == [u8(0x7F), 0x2E, 0x11] // not in the table
	// declared, but the table leaves 0x23 out
	assert s.handle([u8(0x23), 0x12, 0x10, 0x00, 0x01]) == [u8(0x7F), 0x23, 0x11]
}

fn test_a_described_server_without_a_table_serves_them_everywhere() {
	mut s := server_from(ServerSpec{})
	assert s.handle([u8(0x23), 0x12, 0x10, 0x00, 0x01]) == [u8(0x7F), 0x23, 0x11]
	s.declare_memory(0x1000, 4)
	assert s.handle([u8(0x3D), 0x12, 0x10, 0x01, 0x01, 0x5A]) == [u8(0x7D), 0x12, 0x10, 0x01, 0x01]
	assert s.handle([u8(0x23), 0x12, 0x10, 0x00, 0x04]) == [u8(0x63), 0x00, 0x5A, 0x00, 0x00]
}
