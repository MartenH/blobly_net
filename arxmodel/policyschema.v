module arxmodel

// policy.schema.json: the JSON Schema (draft-07) of a policy file, made from policy_settings(),
// for editors that check TOML against one (Taplo, Even Better TOML: `#:schema` on the first
// line). The committed file is this function's output; a test holds them equal.

fn json_str(s string) string {
	return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
}

// json_of is a setting's value, from its TOML spelling, as JSON.
fn json_of(toml_value string) string {
	v := toml_value.trim_space()
	if v.starts_with('{') {
		inner := v.trim('{} ')
		if inner == '' {
			return '{}'
		}
		return '{' + inner.split(', ').map(it.replace('" = "', '": "')).join(', ') + '}'
	}
	return v
}

// setting_schema is one setting's schema.
fn setting_schema(st PolicySetting, def Policy) string {
	mut desc := st.description
	if st.spec != '' {
		desc += ' AUTOSAR: ${st.spec}.'
	}
	mut parts := []string{}
	match st.kind {
		.choice {
			parts << '"type": "string"'
			parts << '"enum": [${st.allowed.map(json_str(it)).join(', ')}]'
		}
		.boolean {
			parts << '"type": "boolean"'
		}
		.names {
			parts << '"type": "array"'
			parts << '"items": {"type": "string", "pattern": "^[A-Za-z_:][-A-Za-z0-9_.:]*$"}'
		}
		.element {
			parts << '"type": "string"'
			parts << '"pattern": "^[A-Za-z_:][-A-Za-z0-9_.:]*$"'
		}
		.table {
			parts << '"type": "object"'
			parts << '"propertyNames": {"pattern": "^[^.]+\\\\.[^.]+$"}'
			parts << '"additionalProperties": {"type": "string", "pattern": "^[^ .]+$"}'
		}
	}
	parts << '"default": ${json_of(st.show(def))}'
	parts << '"description": ${json_str(desc)}'
	return '{' + parts.join(', ') + '}'
}

// severity_key_pattern is the pattern of a [severity] key: a layer, `layer.kind`, or
// `layer.kind:NAME` (`:@NAME` for an attribute).
fn severity_key_pattern() string {
	mut layers := []string{}
	for layer in ['merge', 'xml_schema', 'multiplicity', 'reference', 'policy'] {
		kinds := known_kinds[layer] or { continue }
		// after the kind, an element or @attribute: a name, or an expanded name ({uri}local) as a
		// merge names another namespace's element or a namespaced attribute
		layers << '${layer}(\\\\.(${kinds.join('|')})(:@?([A-Za-z_][-A-Za-z0-9_.:]*|\\\\{[^}]*\\\\}[A-Za-z_][-A-Za-z0-9_.]*))?)?'
	}
	return '^(${layers.join('|')})$'
}

// policy_schema_json is policy.schema.json.
pub fn policy_schema_json() string {
	def := default_policy()
	settings := policy_settings()
	mut tables := []string{}
	for st in settings {
		if st.table !in tables {
			tables << st.table
		}
	}
	mut out := []string{}
	out << '{'
	out << '  "\$schema": "http://json-schema.org/draft-07/schema#",'
	out << '  "\$id": "policy.schema.json",'
	out << '  "title": "arxmodel merge policy",'
	out << '  "description": ${json_str("Every merge choice that is arxmodel's and not read from the AUTOSAR schema (policy.toml, the AUTOSAR specification's; automat.policy.toml, the alternative). Generated by `arxmodel policy --schema`; do not edit.")},'
	out << '  "type": "object",'
	out << '  "additionalProperties": false,'
	out << '  "required": [${tables.map(json_str(it)).join(', ')}],'
	out << '  "properties": {'
	for t in tables {
		ss := settings.filter(it.table == t)
		out << '    ${json_str(t)}: {'
		out << '      "type": "object",'
		out << '      "additionalProperties": false,'
		out << '      "required": [${ss.map(json_str(it.key)).join(', ')}],'
		out << '      "properties": {'
		for k, st in ss {
			comma := if k + 1 < ss.len { ',' } else { '' }
			out << '        ${json_str(st.key)}: ${setting_schema(st, def)}${comma}'
		}
		out << '      }'
		out << '    },'
	}
	out << '    "filter": {'
	out << '      "type": "array",'
	out << '      "description": ${json_str('[[filter]]: severities for the findings each matches, after [severity]; a finding takes the first filter it matches, and a filter that matches nothing is reported (policy.unused_filter).')},'
	out << '      "items": {'
	out << '        "type": "object",'
	out << '        "additionalProperties": false,'
	fields := filter_fields()
	out << '        "required": [${fields.filter(it.required).map(json_str(it.name)).join(', ')}],'
	out << '        "properties": {'
	for k, f in fields {
		comma := if k + 1 < fields.len { ',' } else { '' }
		mut parts := ['"type": "string"']
		if f.enum_values.len > 0 {
			parts << '"enum": [${f.enum_values.map(json_str(it)).join(', ')}]'
		} else {
			parts << '"minLength": 1'
		}
		if f.name == 'match' {
			parts << '"pattern": ${json_str(severity_key_pattern()).replace('\\\\', '\\')}'
		}
		parts << '"description": ${json_str(f.description)}'
		out << '          ${json_str(f.name)}: {${parts.join(', ')}}${comma}'
	}
	out << '        }'
	out << '      }'
	out << '    },'
	out << '    "severity": {'
	out << '      "type": "object",'
	out << '      "description": ${json_str('Each finding\'s severity, by layer, "layer.kind" or "layer.kind:element" ("layer.kind:@attribute"); the most specific applies, and a finding no key names is an error.')},'
	out << '      "propertyNames": {"pattern": ${json_str(severity_key_pattern()).replace('\\\\\\\\', '\\\\')}},'
	out << '      "additionalProperties": {"type": "string", "enum": ["error", "warning", "ignore"]}'
	out << '    }'
	out << '  }'
	out << '}'
	return out.join('\n') + '\n'
}
